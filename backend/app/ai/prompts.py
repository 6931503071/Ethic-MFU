def fillable_fields(template: FormTemplate) -> list[FieldDef]:
    """ช่องที่จะขอให้ AI หา"""
    return [
        f for f in template.iter_fields()
        if f.fill_by == FillBy.AI and f.type in SUPPORTED_TYPES and not f.is_gate
    ]


def _field_spec(f: FieldDef) -> dict:
    spec = {
        "field_id": f.id,
        "type": f.type.value,
        "value_shape": "list of strings" if f.type in LIST_TYPES else "string",
        "label": f.label,
    }
    if f.hint:
        spec["hint"] = f.hint[:200]
    return spec


def build_user_prompt(template: FormTemplate, block_texts: dict[int, str]) -> str:
    fields = [_field_spec(f) for f in fillable_fields(template)]
    doc = "\n".join(f"[B{i}] {t}" for i, t in sorted(block_texts.items()) if t.strip())
    return (
        "ช่องที่ต้องหา (JSON):\n"
        + json.dumps(fields, ensure_ascii=False)
        + "\n\nเอกสาร (แต่ละบรรทัดขึ้นต้นด้วยเลขบล็อก [B<เลข>] ตอนตอบให้ใช้เฉพาะตัวเลข):\n"
        + doc
    )


# =====================================================================
# โหมด "ร่างจาก AI" (draft): AI วิเคราะห์ว่าเนื้อหาส่วนไหนของไฟล์เกี่ยวกับช่องไหน
# แล้วสรุป/เรียบเรียงเป็นร่าง ไม่ต้องให้หัวข้อในไฟล์ตรงกับฟอร์ม
# =====================================================================

def draftable_fields(template: FormTemplate) -> list[FieldDef]:
    """ช่องที่ขอให้ AI ร่างให้ ไม่รวมช่องในหมวดเฉพาะทาง (ยา อาหาร สมุนไพร เครื่องสำอาง
    เครื่องมือแพทย์ ฯลฯ) เพราะต้องให้ผู้ใช้เลือกหมวดเองก่อน ไม่ควรให้ AI เดา"""
    out = []
    for f in fillable_fields(template):
        if f.section_id and any(s.gate is not None for s in template.section_chain(f.section_id)):
            continue
        out.append(f)
    return out


